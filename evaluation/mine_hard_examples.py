"""python -m evaluation.mine_hard_examples --checkpoint X [--dataset data/v001] [--out configs/hard.yaml]
Groups failures by font/language/doc-type/tier → writes rebalanced hard-example config."""
import argparse, json, os
import sys as _sys
from pathlib import Path as _Path
_r = _Path(__file__).resolve().parent
while not (_r / "src" / "env_bootstrap.py").exists():
    if _r == _r.parent:
        break
    _r = _r.parent
_sys.path.insert(0, str(_r / "src"))
import env_bootstrap  # noqa: F401,E402  (pins all caches to external drive)
from pathlib import Path
from collections import Counter
ROOT = Path(os.environ.get("OCR_ROOT", str(Path(__file__).resolve().parents[1])))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--checkpoint", required=True)
    ap.add_argument("--dataset", default="data/v001")
    ap.add_argument("--eval-report", default=None)
    ap.add_argument("--out", default="configs/hard_examples.yaml")
    a = ap.parse_args()
    rep_path = Path(a.eval_report) if a.eval_report else None
    if rep_path is None:
        # latest experiments/eval_* report
        cands = sorted((ROOT / "experiments").glob("eval_*/evaluation_report.json"))
        if not cands:
            print("No eval report found. Run python -m evaluation.evaluate first."); raise SystemExit(2)
        rep_path = cands[-1]
    rep = json.loads(Path(rep_path).read_text())
    fails = rep.get("failures", [])
    by_type, by_lang = Counter(), Counter()
    for f in fails:
        by_type[f["meta"].get("document_type", "?")] += 1
        by_lang[f["meta"].get("language", "?")] += 1
    tot = max(1, len(fails))
    # boost failing categories (min 10%, scale by failure share)
    types = {k: round(0.10 + 0.9 * v / tot, 3) for k, v in by_type.items()}
    s = sum(types.values()); types = {k: round(v / s, 3) for k, v in types.items()}
    langs = {k: round(0.15 + 0.85 * v / tot, 3) for k, v in by_lang.items()}
    s = sum(langs.values()); langs = {k: round(v / s, 3) for k, v in langs.items()}
    out = ROOT / a.out if not str(a.out).startswith(str(ROOT)) else Path(a.out)
    out.write_text("# auto-generated by mine_hard_examples\n" + f"# source: {rep_path}\n# failures: {len(fails)}\n" +
        f"dataset: {{count: 2000, seed: 43, dpi: 200, languages: {langs}, document_types: {types}}}\n")
    print(f"failures={len(fails)} by_type={dict(by_type)} by_lang={dict(by_lang)}")
    print(f"wrote → {out}")

if __name__ == "__main__":
    main()
